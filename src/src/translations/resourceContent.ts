/**
 * Returns localized resource without mutating original database or state.
 * Preserves user-created resources verbatim without overwriting.
 */
export function getLocalizedResource(resource: Resource, lang: Language): Resource {
  if (lang === 'hi' || lang === 'mr') {
    const translated = SEED_RESOURCE_TRANSLATIONS[lang]?.[resource.id];
    if (translated) {
      return {
        ...resource,
        title: translated.title || resource.title,
        description: translated.description || resource.description,
        provider: translated.provider || resource.provider,
        season_climate: translated.season_climate || resource.season_climate,
        eligibility: translated.eligibility || resource.eligibility,
        benefits: translated.benefits || resource.benefits,
        category_name: translated.category_name || resource.category_name
      };
    }
  }
  return resource;
}
